@app.route("/world/new", methods=["POST"])
def create_world():
    world = new_world()
    build_story_tree(world)

    return jsonify({
        "success": True,
        "world": world
    })


# ============================================================
# GET WORLD
# ============================================================

@app.route("/world/<world_id>", methods=["GET"])
def get_world(world_id):
    world = worlds.get(world_id)

    if not world:
        return jsonify({
            "error": "World not found"
        }), 404

    return jsonify({
        "success": True,
        "world": world
    })


# ============================================================
# RESET WORLD
# ============================================================

@app.route("/world/<world_id>/reset", methods=["POST"])
def reset_world(world_id):
    if world_id in worlds:
        del worlds[world_id]

    world = new_world()
    build_story_tree(world)

    return jsonify({
        "success": True,
        "world": world
    })


# ============================================================
# CHAT / STORY
# ============================================================

@app.route("/chat", methods=["POST"])
def chat():
    data = request.get_json(silent=True) or {}

    world_id = data.get("world_id")
    message = data.get("message", "").strip()

    if not world_id:
        return jsonify({
            "error": "No world selected."
        }), 400

    if not message:
        return jsonify({
            "error": "Message cannot be empty."
        }), 400

    world = worlds.get(world_id)

    if not world:
        return jsonify({
            "error": "World not found."
        }), 404

    if world["finished"]:
        return jsonify({
            "error": "This world has already ended.",
            "world": world
        }), 400

    try:
        result = ask_ai(world, message)

        world["turn"] += 1

        world["location"] = result.get(
            "location",
            world["location"]
        )

        world["choices"].append(message)

        memory = result.get("new_memory")

        if memory:
            world["memories"].append(memory)

        node_id = str(uuid.uuid4())[:8]

        parent = world["current_node"]

        node_title = result.get(
            "node_title",
            f"Chapter {world['turn']}"
        )

        world["story_nodes"][node_id] = {
            "title": node_title,
            "parent": parent,
            "choice": message,
            "turn": world["turn"],
            "location": world["location"],
            "status": "visited",
            "choices": result.get("choices", [])
        }

        world["current_node"] = node_id
        world["visited_nodes"].append(node_id)

        ending = result.get("ending")

        if ending in ENDING_TYPES:
            world["ending"] = ending
            world["finished"] = True

        return jsonify({
            "success": True,
            "story": result.get("story", ""),
            "choices": result.get("choices", []),
            "location": world["location"],
            "ending": world["ending"],
            "world": world
        })

    except Exception as e:
        return jsonify({
            "error": str(e)
        }), 500


