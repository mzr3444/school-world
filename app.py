import os
import uuid
import random
from flask import Flask, request, jsonify, render_template
from openai import OpenAI

app = Flask(__name__)

# ============================================================
# OPENROUTER
# ============================================================

API_KEY = os.environ.get("OPENROUTER_API_KEY")
MODEL = os.environ.get("OPENROUTER_MODEL", "openai/gpt-oss-20b")

client = None

if API_KEY:
    client = OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=API_KEY
    )

# ============================================================
# WORLD / STORY STORAGE
# ============================================================

worlds = {}

ENDING_TYPES = [
    "hopeful",
    "tragic",
    "mysterious",
    "rebellion",
    "peaceful",
    "bittersweet",
    "unknown"
]


def new_world():
    world_id = str(uuid.uuid4())

    world = {
        "id": world_id,
        "name": random.choice([
            "Echoes of Tomorrow",
            "The Last Bell",
            "Shadows of Choice",
            "A World Between",
            "The Unwritten Day",
            "Fragments",
            "After the Signal"
        ]),
        "turn": 0,
        "location": "Classroom",
        "memories": [],
        "characters": {},
        "choices": [],
        "story_nodes": {},
        "current_node": "start",
        "ending": None,
        "finished": False,
        "visited_nodes": [],
        "created": True
    }

    worlds[world_id] = world
    return world


# ============================================================
# STORY TREE
# ============================================================

def build_story_tree(world):
    """
    Creates a unique branching structure for every world.

    The exact story is generated by the AI, but the server keeps
    track of every node the player visits.
    """

    if world["story_nodes"]:
        return

    first_names = [
        "Alex", "Jordan", "Maya", "Eli",
        "Sam", "Riley", "Noah", "Taylor"
    ]

    world["characters"] = {
        "main_character": random.choice(first_names),
        "friend": random.choice(first_names),
        "mysterious_character": random.choice(first_names)
    }

    world["story_nodes"]["start"] = {
        "title": "The Beginning",
        "parent": None,
        "choices": [],
        "status": "current"
    }


def make_story_prompt(world, player_message):
    history = world["memories"][-20:]

    character = world["characters"].get("main_character", "the main character")
    friend = world["characters"].get("friend", "their friend")
    mysterious = world["characters"].get(
        "mysterious_character",
        "the mysterious person"
    )

    return f"""
You are the story engine for a long-running interactive game.

The game is a branching story inspired by cinematic choice-based
games. Every player decision must have consequences later.

IMPORTANT:
- Never reset the story unless the user explicitly creates/resets a world.
- Remember previous choices.
- Characters remember important events.
- Characters should react naturally to the player's actions.
- Do not simply repeat the player's instructions.
- If the player says they travel somewhere, describe the travel and
  have characters react naturally instead of treating the travel
  instruction as dialogue.
- The player controls their own character.
- NPCs control themselves.
- NPCs may disagree with the player.
- NPCs may misunderstand things.
- NPC relationships can change.
- Earlier choices should affect later dialogue and events.
- Do not make every choice obviously good or bad.
- Some consequences should happen much later.
- Do not force an ending too quickly.
- Keep the story cinematic and detailed.
- Write several paragraphs when appropriate.
- Give meaningful choices at the end.
- Choices should be different enough that they lead to different
  future events.
- The story should be capable of reaching at least five major endings.

MAIN CHARACTER:
{character}

FRIEND:
{friend}

MYSTERIOUS CHARACTER:
{mysterious}

CURRENT LOCATION:
{world["location"]}

TURN:
{world["turn"]}

PREVIOUS CHOICES:
{world["choices"][-15:]}

IMPORTANT MEMORIES:
{history}

CURRENT PLAYER ACTION:
{player_message}

Return JSON with EXACTLY these fields:

{{
  "story": "the next section of the story",
  "location": "current location",
  "choices": [
      "choice 1",
      "choice 2",
      "choice 3"
  ],
  "new_memory": "one important event to remember",
  "node_title": "short title for this story node",
  "ending": null
}}

If the story genuinely reaches an ending, "ending" must contain
one of:

hopeful
tragic
mysterious
rebellion
peaceful
bittersweet
unknown

Otherwise ending must be null.
"""


def ask_ai(world, player_message):
    if not client:
        raise RuntimeError(
            "OPENROUTER_API_KEY is missing. Add it to Render Environment Variables."
        )

    prompt = make_story_prompt(world, player_message)

    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": (
                    "You are a branching interactive story engine. "
                    "Return valid JSON only."
                )
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.9,
        max_tokens=1800
    )

    text = response.choices[0].message.content.strip()

    # Remove accidental markdown fences
    if text.startswith("```"):
        lines = text.splitlines()

        if lines and lines[0].startswith("```"):
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        text = "\n".join(lines).strip()

    import json

    try:
        return json.loads(text)
    except json.JSONDecodeError:
        # Fallback if model didn't return perfect JSON
        return {
            "story": text,
            "location": world["location"],
            "choices": [
                "Continue",
                "Investigate",
                "Ask someone what is happening"
            ],
            "new_memory": player_message,
            "node_title": "A New Moment",
            "ending": None
        }


